#!/usr/bin/env python3
"""Generate nfkd_data.zig: Unicode NFKD tables for BIP-39 normalization.

Run:
  python3 -I packages/voltaire-zig/src/crypto/nfkd_data_gen.py > packages/voltaire-zig/src/crypto/nfkd_data.zig
  zig fmt packages/voltaire-zig/src/crypto/nfkd_data.zig

Source of truth is Python's unicodedata (UnicodeData.txt). Hangul syllables
are decomposed algorithmically in nfkd.zig and are excluded here.
"""
import sys
import unicodedata as u

keys, offs, lens, data = [], [], [], bytearray()
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
        continue
    c = chr(cp)
    d = u.normalize("NFKD", c)
    if d == c:
        continue
    b = d.encode("utf-8")
    keys.append(cp)
    offs.append(len(data))
    lens.append(len(b))
    data += b

ranges = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    ccc = u.combining(chr(cp))
    if not ccc:
        continue
    if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == ccc:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, ccc])

assert len(data) < 1 << 16 and max(lens) < 256

out = sys.stdout
out.write("//! GENERATED by nfkd_data_gen.py from Unicode %s. Do not edit.\n" % u.unidata_version)
out.write("//! Full (recursive) NFKD decompositions and canonical combining classes.\n\n")
out.write("pub const unicode_version = \"%s\";\n\n" % u.unidata_version)

def arr(name, ty, vals, per=12):
    out.write("pub const %s = [_]%s{\n" % (name, ty))
    for i in range(0, len(vals), per):
        out.write("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",\n")
    out.write("};\n\n")

arr("decomp_keys", "u21", keys)
arr("decomp_offsets", "u16", offs)
arr("decomp_lengths", "u8", lens, 24)
out.write("/// UTF-8 bytes of every decomposition, concatenated.\n")
out.write("pub const decomp_data: []const u8 =\n")
for i in range(0, len(data), 32):
    out.write('    "' + "".join("\\x%02x" % x for x in data[i:i + 32]) + '"')
    out.write(" ++\n" if i + 32 < len(data) else ";\n\n")
out.write("/// Inclusive code point ranges with a nonzero canonical combining class.\n")
out.write("pub const CccRange = struct { lo: u21, hi: u21, ccc: u8 };\n\n")
out.write("pub const ccc_ranges = [_]CccRange{\n")
for lo, hi, c in ranges:
    out.write("    .{ .lo = %d, .hi = %d, .ccc = %d },\n" % (lo, hi, c))
out.write("};\n")
